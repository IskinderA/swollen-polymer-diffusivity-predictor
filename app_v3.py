"""
Streamlit application for Swollen Polymer Diffusivity Predictor v3.

v3 changes relative to the previous public application:
- Version-12 prospective deployment models trained on 2095 observations across 28 polymers;
- Baseline applicability-gated hybrid (AGH) is the headline prediction;
- QRF and MLP constituent predictions remain visible;
- applicability distance, learned cutoff, and selected constituent are reported explicitly;
- model-derived prediction distributions remain distinct from requested Monte Carlo samples;
- complete v3 CSV/JSON download support.

Run locally from the repository root with:

    streamlit run app_v3.py
"""

