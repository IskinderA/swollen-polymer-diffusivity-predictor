    with col3:
        solute_options = get_solutes(polymer, solvent)
        solute = st.selectbox("Solute", solute_options, index=0)

    system = get_system(polymer, solvent, solute)

    with st.container(border=True):
        st.subheader("Known System Information")
        st.success(
            "System recognized. Properties below were automatically populated "
            "from the curated Known System database."
        )

        info_col1, info_col2 = st.columns(2)

        with info_col1:
            st.write(
                f"**Glass-transition temperature (Tg):** "
                f"{float(system['Tg_K']):.2f} K"
            )
            st.write(
                f"**Polymer crystallinity (Xc):** "
                f"{float(system['Polymer_Xc']):.3f}"
            )
            st.write(f"**Polymer CHRIS category:** {system['CHRIS_Category']}")

        with info_col2:
            smiles_value = system.get("Solute_SMILES", "")
            cas_value = system.get("Solute_CAS", "")

            st.write(
                f"**Solute/Penetrant SMILES:** "
                f"{smiles_value if str(smiles_value) != 'nan' else 'Not available'}"
            )
            st.write(
                f"**Solute/Penetrant CAS:** "
                f"{cas_value if str(cas_value) != 'nan' else 'Not available'}"
            )

    temperature = st.number_input("Temperature, T (K)", value=298.15)
    mass_ratio = st.number_input("Swollen/dry mass ratio", value=1.10)

    rho_polymer = st.number_input(
        "Polymer density (g/cc)",
        value=1.05,
        key="known_rho_polymer",
    )

    rho_solvent = st.number_input(
        "Solvent density (g/cc)",
        value=0.79,
        key="known_rho_solvent",
    )

    st.subheader("Monte Carlo Sampling")
    n_samples = st.number_input(
        "Number of Monte Carlo samples to generate",
        min_value=100,
        max_value=10000,
        value=1000,
        step=100,
        key="known_n_samples",
    )

    st.caption(
        "The trained-model prediction distributions are fixed at 300 QRF, "
        "20 MLP, and 6000 consensus values. This control sets only the number "
        "of Monte Carlo draws sampled with replacement from those fixed "
        "distributions."
    )

    if st.button("Predict", key="known_predict", type="primary"):
        system = get_system(polymer, solvent, solute)

        inputs = SimplePredictorInputs(
            temperature_k=temperature,
            tg_k=float(system["Tg_K"]),
            mass_ratio=mass_ratio,
            rho_polymer=rho_polymer,
            rho_solvent=rho_solvent,
            polymer_xc=float(system["Polymer_Xc"]),
            chris_category=str(system["CHRIS_Category"]),
            smiles=(
                str(system["Solute_SMILES"])
                if str(system.get("Solute_SMILES", "")) != "nan"
                else ""
            ),
            cas=(
                str(system["Solute_CAS"])
                if str(system.get("Solute_CAS", "")) != "nan"
                else ""
            ),
            n_samples=int(n_samples),
        )

        try:
            pred = predict(inputs)
        except Exception as exc:
            st.error(f"Prediction failed: {exc}")
            st.stop()

        show_prediction_summary(pred, inputs)


