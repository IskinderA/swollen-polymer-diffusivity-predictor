APP_VERSION = "2.0"


def compute_descriptors_v2(inputs: SimplePredictorInputs) -> dict:
    """Return descriptors generated by the same v2 reference wrapper used for prediction."""

    return wrapper_v2.build_inputs_from_simple_interface(
        T=inputs.temperature_k,
        Tg_K=inputs.tg_k,
        mass_ratio=inputs.mass_ratio,
        rho_polymer=inputs.rho_polymer,
        rho_solvent=inputs.rho_solvent,
        Polymer_Xc=inputs.polymer_xc,
        CHRIS_Category=inputs.chris_category,
        smiles=inputs.smiles or None,
        cas=inputs.cas or None,
    )


def show_disclaimer() -> None:
    with st.expander("Research Use Disclaimer", expanded=False):
        st.write(RESEARCH_USE_DISCLAIMER)
        st.markdown(
            "- [CDRH Regulatory Science Tool (RST) Catalog](https://cdrh-rst.fda.gov/)\n"
            "- [Medical Device Development Tool (MDDT) Program](https://www.fda.gov/medical-devices/medical-device-development-tools-mddt)"
        )


def _show_distribution_metrics(
    title: str,
    *,
    p5: float,
    p50: float,
    p95: float,
    n: int,
    caption: str,
) -> None:
    """Render compact p5/p50/p95 model-derived distribution metrics."""

    st.subheader(title)
    st.caption(caption)
    c1, c2, c3 = st.columns(3)
    c1.metric("p5 log10(D)", f"{p5:.3f}")
    c2.metric("p50 log10(D)", f"{p50:.3f}")
    c3.metric("p95 log10(D)", f"{p95:.3f}")
    st.caption(f"Fixed model-derived distribution size: n = {n:,}")


def _show_mc_metrics(title: str, summary) -> None:
    """Render requested Monte Carlo sample summary."""

    st.markdown(f"**{title}**")
    c1, c2, c3, c4 = st.columns(4)
    c1.metric("MC p5", f"{summary.p5:.3f}")
    c2.metric("MC p50", f"{summary.p50:.3f}")
    c3.metric("MC p95", f"{summary.p95:.3f}")
    c4.metric("MC n", f"{summary.n:,}")


def show_prediction_summary(
    pred: PredictionResult,
    inputs: SimplePredictorInputs,
) -> None:
    """Render the complete v2 prediction result."""

    st.divider()
    st.header("Prediction Summary")

    # ------------------------------------------------------------------
    # Headline consensus result
    # ------------------------------------------------------------------
    with st.container(border=True):
        st.subheader("Headline Prediction — Equal-Weight Consensus")
        st.caption(
            "Recommended central prediction: 0.5 × QRF p50 + 0.5 × MLP p50 "
            "in log10(D) space."
        )

        h1, h2 = st.columns(2)
        h1.metric(
            "Consensus log10(D) [cm²/s]",
            f"{pred.consensus_central_log10D:.3f}",
        )
        h2.metric(
            "Consensus D [cm²/s]",
            f"{pred.consensus_central_D:.3e}",
        )

        p1, p2, p3 = st.columns(3)
        p1.metric(
            "Consensus distribution p5 log10(D)",
            f"{pred.consensus.p5:.3f}",
        )
        p2.metric(
            "Consensus distribution p50 log10(D)",
            f"{pred.consensus_distribution_p50:.3f}",
        )
        p3.metric(
            "Consensus distribution p95 log10(D)",
            f"{pred.consensus.p95:.3f}",
        )

        st.caption(
            f"The consensus model-derived prediction distribution contains "
            f"{pred.n_consensus_pairs:,} values from all "
            f"{pred.n_qrf_tree_predictions} QRF-tree × "
            f"{pred.n_mlp_ensemble_members} MLP-network pairings. "
            "Its distribution median is reported separately from the manuscript-defined "
            "headline consensus central prediction."
        )

    # ------------------------------------------------------------------
    # Inputs and descriptors
    # ------------------------------------------------------------------
    st.subheader("Inputs Used")
    input_col1, input_col2 = st.columns(2)

    with input_col1:
        st.write(f"**Tg:** {inputs.tg_k:.2f} K")
        st.write(f"**Temperature:** {inputs.temperature_k:.2f} K")
        st.write(f"**Swollen/dry mass ratio:** {inputs.mass_ratio:.3f}")
        st.write(f"**Polymer density:** {inputs.rho_polymer:.3f} g/cc")

    with input_col2:
        st.write(f"**Solvent density:** {inputs.rho_solvent:.3f} g/cc")
        st.write(f"**Crystallinity, Xc:** {inputs.polymer_xc:.3f}")
        st.write(f"**Polymer CHRIS category:** {inputs.chris_category}")
        st.write(
            f"**Solute/Penetrant SMILES:** "
            f"{inputs.smiles if inputs.smiles else 'Not provided'}"
        )
        st.write(
            f"**Solute/Penetrant CAS:** "
            f"{inputs.cas if inputs.cas else 'Not provided'}"
        )
        st.write(f"**Requested Monte Carlo samples:** {inputs.n_samples:,}")

    with st.expander("Show computed descriptors"):
        st.json(compute_descriptors_v2(inputs))

    # ------------------------------------------------------------------
    # Constituent model-derived distributions
    # ------------------------------------------------------------------
    st.subheader("Constituent Predictors")

    qrf_col, mlp_col = st.columns(2)

    with qrf_col:
        _show_distribution_metrics(
            "QRF Prediction Distribution",
            p5=pred.qrf.p5,
            p50=pred.qrf.p50,
            p95=pred.qrf.p95,
            n=pred.qrf.n,
            caption=(
                "Percentiles calculated directly from the 300 trained-tree "
                "predictions."
            ),
        )

    with mlp_col:
        _show_distribution_metrics(
            "MLP Ensemble Prediction Distribution",
            p5=pred.mlp.p5,
            p50=pred.mlp.p50,
            p95=pred.mlp.p95,
            n=pred.mlp.n,
            caption=(
                "Percentiles calculated directly from the 20 independently "
                "initialized network predictions."
            ),
        )

    # ------------------------------------------------------------------
    # Agreement
    # ------------------------------------------------------------------
    delta = abs(pred.qrf.p50 - pred.mlp.p50)
    agreement_label, agreement_text = classify_model_agreement(delta)

    st.subheader("QRF–MLP Agreement")
    st.write(f"**{agreement_label}**")
    st.write(
        f"Difference between QRF and MLP central predictions: "
        f"**{delta:.3f} log units**"
    )
    st.write(agreement_text)

    # ------------------------------------------------------------------
    # Prediction-distribution vs requested MC distinction
    # ------------------------------------------------------------------
    st.subheader("Model-Derived vs. Monte Carlo Distributions")

    st.write(
        "The model-derived prediction distributions are fixed by the trained "
        "models: QRF has 300 values, MLP has 20 values, and the consensus has "
        "6000 pairwise values. The requested Monte Carlo distributions are "
        "separate resamples drawn with replacement from those fixed empirical "
        "distributions."
    )

    with st.expander("Show requested Monte Carlo sample summaries"):
        _show_mc_metrics("QRF Monte Carlo sample", pred.qrf_sample)
        _show_mc_metrics("MLP Monte Carlo sample", pred.mlp_sample)
        _show_mc_metrics("Consensus Monte Carlo sample", pred.consensus_sample)

        st.info(
            "Monte Carlo sample percentiles may differ slightly from the "
            "model-derived prediction-distribution percentiles, especially for "
            "smaller requested sample sizes. Changing the requested sample size "
            "does not change the trained-model prediction distributions."
        )

    with st.expander("How the consensus distribution is constructed"):
        st.write(
            "For each system, the application retains all 300 QRF tree-level "
            "predictions and all 20 MLP-network predictions. Every QRF prediction "
            "is paired with every MLP prediction, and each pair is averaged with "
            "equal weight in log10(D) space."
        )
        st.code(
            "300 QRF tree predictions × 20 MLP network predictions = "
            "6000 consensus prediction-distribution values",
            language=None,
        )
        st.write(
            "Consensus p5 and p95 are calculated directly from those 6000 values. "
            "The headline consensus central prediction remains the equal-weight "
            "average of the QRF and MLP medians."
        )

    with st.expander("Interpretation of empirical prediction variability"):
        st.write(
            "QRF variability reflects tree-to-tree variation within the trained "
            "random forest. MLP variability reflects prediction variation across "
            "20 independently initialized neural networks. Consensus variability "
            "reflects all 6000 equal-weight pairings of those constituent model "
            "predictions. These empirical distributions are useful measures of "
            "prediction variability but are not formally calibrated probabilistic "
            "confidence or credible intervals."
        )

        st.write(
            "Model agreement is based on the absolute difference between the QRF "
            "and MLP central predictions in log10(D) units:"
        )
        st.markdown(
            "- **Excellent/small disagreement:** < 0.25 log units\n"
            "- **Moderate disagreement:** 0.25–0.75 log units\n"
            "- **Large disagreement:** > 0.75 log units"
        )

    # ------------------------------------------------------------------
    # Downloads
    # ------------------------------------------------------------------
    st.subheader("Downloads")
    st.caption(
        "v2 separates compact summaries, fixed model-derived prediction "
        "distributions, and requested Monte Carlo samples."
    )

    d1, d2 = st.columns(2)
    with d1:
        st.download_button(
            "Download prediction summary CSV",
            data=prediction_summary_csv(pred=pred, inputs=inputs),
            file_name="prediction_summary_v2.csv",
            mime="text/csv",
            use_container_width=True,
        )
        st.download_button(
            "Download model-derived distributions CSV",
            data=prediction_distributions_csv(pred),
            file_name="prediction_distributions_v2.csv",
            mime="text/csv",
            use_container_width=True,
        )
        st.download_button(
            "Download Monte Carlo samples CSV",
            data=monte_carlo_samples_csv(pred),
            file_name="monte_carlo_samples_v2.csv",
            mime="text/csv",
            use_container_width=True,
        )

    with d2:
        st.download_button(
            "Download prediction summary JSON",
            data=prediction_summary_json(pred=pred, inputs=inputs),
            file_name="prediction_summary_v2.json",
            mime="application/json",
            use_container_width=True,
        )
        st.download_button(
            "Download complete prediction JSON",
            data=prediction_full_json(pred=pred, inputs=inputs),
            file_name="prediction_full_v2.json",
            mime="application/json",
            use_container_width=True,
        )


