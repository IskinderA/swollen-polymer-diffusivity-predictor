def compute_descriptors_v3(inputs: SimplePredictorInputs) -> dict:
    """Return descriptors generated by the same v3 reference wrapper used for prediction."""

    return wrapper_v3.build_inputs_from_simple_interface(
        T=inputs.temperature_k,
        Tg_K=inputs.tg_k,
        mass_ratio=inputs.mass_ratio,
        rho_polymer=inputs.rho_polymer,
        rho_solvent=inputs.rho_solvent,
        Polymer_Xc=inputs.polymer_xc,
        CHRIS_Category=inputs.chris_category,
        smiles=inputs.smiles or None,
        cas=inputs.cas or None,
    )


def show_disclaimer() -> None:
    with st.expander("Research Use Disclaimer", expanded=False):
        st.write(RESEARCH_USE_DISCLAIMER)
        st.markdown(
            "- [CDRH Regulatory Science Tool (RST) Catalog](https://cdrh-rst.fda.gov/)\n"
            "- [Medical Device Development Tool (MDDT) Program](https://www.fda.gov/medical-devices/medical-device-development-tools-mddt)"
        )


def _show_distribution_metrics(
    title: str,
    *,
    p5: float,
    p50: float,
    p95: float,
    n: int,
    caption: str,
) -> None:
    """Render compact p5/p50/p95 model-derived distribution metrics."""

    st.subheader(title)
    st.caption(caption)
    c1, c2, c3 = st.columns(3)
    c1.metric("p5 log10(D)", f"{p5:.3f}")
    c2.metric("p50 log10(D)", f"{p50:.3f}")
    c3.metric("p95 log10(D)", f"{p95:.3f}")
    st.caption(f"Fixed model-derived distribution size: n = {n:,}")


def _show_mc_metrics(title: str, summary) -> None:
    """Render requested Monte Carlo sample summary."""

    st.markdown(f"**{title}**")
    c1, c2, c3, c4 = st.columns(4)
    c1.metric("MC p5", f"{summary.p5:.3f}")
    c2.metric("MC p50", f"{summary.p50:.3f}")
    c3.metric("MC p95", f"{summary.p95:.3f}")
    c4.metric("MC n", f"{summary.n:,}")


def show_prediction_summary(
    pred: PredictionResult,
    inputs: SimplePredictorInputs,
) -> None:
    """Render the complete v3 Baseline-AGH prediction result."""

    st.divider()
    st.header("Prediction Summary")

    with st.container(border=True):
        st.subheader("Headline Prediction — Baseline AGH")
        st.caption(
            "Applicability-gated central prediction: MLP is selected when the query "
            "lies within the learned Baseline applicability region; QRF is selected otherwise."
        )
        h1,h2=st.columns(2)
        h1.metric("AGH log10(D) [cm²/s]",f"{pred.agh_central_log10D:.3f}")
        h2.metric("AGH D [cm²/s]",f"{pred.agh_central_D:.3e}")

        a1,a2,a3,a4=st.columns(4)
        a1.metric("Selected model",pred.selected_model)
        a2.metric("Mahalanobis distance",f"{pred.mahalanobis_distance:.3f}")
        a3.metric("AGH cutoff",f"{pred.mahalanobis_cutoff:.3f}")
        a4.metric("Applicability",("Within" if pred.inside_applicability_region else "Beyond"))

        if pred.inside_applicability_region:
            st.success(f"{pred.applicability_status} — MLP selected.")
        else:
            st.warning(f"{pred.applicability_status} — QRF selected.")

        st.caption(
            f"AGH uses the selected {pred.selected_model} empirical prediction distribution "
            f"(n = {pred.n_agh_distribution_values:,}) for variability summaries and Monte Carlo sampling."
        )

    st.subheader("Inputs Used")
    c1,c2=st.columns(2)
    with c1:
        st.write(f"**Tg:** {inputs.tg_k:.2f} K")
        st.write(f"**Temperature:** {inputs.temperature_k:.2f} K")
        st.write(f"**Swollen/dry mass ratio:** {inputs.mass_ratio:.3f}")
        st.write(f"**Polymer density:** {inputs.rho_polymer:.3f} g/cc")
    with c2:
        st.write(f"**Solvent density:** {inputs.rho_solvent:.3f} g/cc")
        st.write(f"**Crystallinity, Xc:** {inputs.polymer_xc:.3f}")
        st.write(f"**Polymer CHRIS category:** {inputs.chris_category}")
        st.write(f"**Solute/Penetrant SMILES:** {inputs.smiles if inputs.smiles else 'Not provided'}")
        st.write(f"**Solute/Penetrant CAS:** {inputs.cas if inputs.cas else 'Not provided'}")
        st.write(f"**Requested Monte Carlo samples:** {inputs.n_samples:,}")

    with st.expander("Show computed Baseline descriptors"):
        st.json(compute_descriptors_v3(inputs))

    st.subheader("Constituent Predictors")
    qrf_col,mlp_col=st.columns(2)
    with qrf_col:
        _show_distribution_metrics(
            "QRF Prediction Distribution",p5=pred.qrf.p5,p50=pred.qrf.p50,p95=pred.qrf.p95,
            n=pred.qrf.n,caption="Percentiles calculated directly from the 300 trained-tree predictions."
        )
    with mlp_col:
        _show_distribution_metrics(
            "MLP Ensemble Prediction Distribution",p5=pred.mlp.p5,p50=pred.mlp.p50,p95=pred.mlp.p95,
            n=pred.mlp.n,caption="Percentiles calculated directly from the 20 independently initialized network predictions."
        )

    _show_distribution_metrics(
        f"AGH Selected Prediction Distribution — {pred.selected_model}",
        p5=pred.agh.p5,p50=pred.agh.p50,p95=pred.agh.p95,n=pred.agh.n,
        caption="AGH inherits the empirical prediction distribution of the constituent selected by the applicability gate."
    )

    with st.expander("Applicability and model diagnostics"):
        st.write(f"**Mahalanobis distance, d_M:** {pred.mahalanobis_distance:.4f}")
        st.write(f"**Learned deployment cutoff:** {pred.mahalanobis_cutoff:.4f}")
        st.write(f"**Selected constituent:** {pred.selected_model}")
        st.write(f"**QRF–MLP central-prediction difference:** {pred.qrf_mlp_difference_log10D:.3f} log units")
        st.caption(
            "Mahalanobis distance is an applicability coordinate, not a calibrated probability of prediction error. "
            "QRF–MLP disagreement is retained as a secondary diagnostic and is not interpreted as a confidence measure."
        )

    st.subheader("Model-Derived vs. Monte Carlo Distributions")
    st.write(
        "The trained-model prediction distributions are fixed at 300 QRF tree predictions and "
        "20 MLP ensemble predictions. Baseline AGH uses the empirical distribution of whichever "
        "constituent is selected by the applicability gate. Requested Monte Carlo distributions "
        "are separate samples drawn with replacement from these fixed empirical distributions."
    )
    with st.expander("Show requested Monte Carlo sample summaries"):
        _show_mc_metrics("QRF Monte Carlo sample",pred.qrf_sample)
        _show_mc_metrics("MLP Monte Carlo sample",pred.mlp_sample)
        _show_mc_metrics("Baseline AGH Monte Carlo sample",pred.agh_sample)
        st.info(
            "Changing the requested sample size does not change the trained-model prediction distributions "
            "or the AGH routing decision."
        )

    with st.expander("Interpretation of empirical prediction variability"):
        st.write(
            "QRF variability reflects tree-to-tree variation within the trained random forest. "
            "MLP variability reflects prediction variation across 20 independently initialized neural networks. "
            "AGH variability is the variability of the constituent selected for the query."
        )
        st.write(
            "These empirical distributions are useful measures of prediction variability but are not "
            "formally calibrated probabilistic confidence or credible intervals."
        )

    st.subheader("Downloads")
    st.caption(
        "v3 separates compact summaries, fixed model-derived prediction distributions, and requested Monte Carlo samples."
    )
    d1,d2=st.columns(2)
    with d1:
        st.download_button("Download prediction summary CSV",
            data=prediction_summary_csv(pred=pred,inputs=inputs),
            file_name="prediction_summary_v3.csv",mime="text/csv",use_container_width=True)
        st.download_button("Download model-derived distributions CSV",
            data=prediction_distributions_csv(pred),
            file_name="prediction_distributions_v3.csv",mime="text/csv",use_container_width=True)
        st.download_button("Download Monte Carlo samples CSV",
            data=monte_carlo_samples_csv(pred),
            file_name="monte_carlo_samples_v3.csv",mime="text/csv",use_container_width=True)
    with d2:
        st.download_button("Download prediction summary JSON",
            data=prediction_summary_json(pred=pred,inputs=inputs),
            file_name="prediction_summary_v3.json",mime="application/json",use_container_width=True)
        st.download_button("Download complete prediction JSON",
            data=prediction_full_json(pred=pred,inputs=inputs),
            file_name="prediction_full_v3.json",mime="application/json",use_container_width=True)


